import assert from 'node:assert/strict';
import { assess, assessMany, portfolioAudit, pulseSnapshot } from '../../web/engine/index.js';
import { mockFetch, setPngEncoder } from '../../web/engine/mock.js';
import { encodePng } from '../../web/engine/vendor/imgdecode.js';
setPngEncoder(encodePng);
const fetch = mockFetch();
const t0 = Date.now();
const events = [];
const r = await assess({ lat: 22.9957, lon: 72.3759, asset_type: 'residential', built_up_sqft: 1200, loan_amount: 4000000, declared_value: 9000000 }, { fetch, onEvent: (e) => events.push(e) });
console.log('full assess ms', Date.now() - t0, 'sources ok', r.provenance.live_sources_ok, '/', r.provenance.live_sources_called);
for (const s of r.sources) console.log(' ', s.id.padEnd(12), s.status, s.ms, s.error || '');
console.log(JSON.stringify({ score: r.score, valuation: r.valuation, liquidity: r.liquidity, hazards: r.hazards, lending: r.lending, land_use: r.land_use, decision: r.decision }, null, 1));
console.log('flags', r.flags.map((f) => f.code));
console.log(r.summary);
assert.equal(r.sources.filter((s) => s.status !== 'ok').length, 0, 'all mocked sources should succeed');
assert.ok(r.score.cqs > 0 && r.score.cqs <= 100);
assert.ok(r.valuation.p10 < r.valuation.p50 && r.valuation.p50 < r.valuation.p90);
assert.ok(r.liquidity.realisable_value < r.valuation.p50);
assert.ok(events.some((e) => e.type === 'done'));
const agri = await assess({ lat: 22.889, lon: 72.223, asset_type: 'agri_land', area_sqm: 12000, loan_amount: 700000 }, { fetch });
console.log('agri', agri.score, agri.valuation.p50, agri.signals.ndvi_max, agri.flags.map((f) => f.code));
const poly = await assess({ polygon: [[72.26, 22.988], [72.2652, 22.988], [72.2652, 22.9915], [72.26, 22.9915]], asset_type: 'industrial', mode: 'fast' }, { fetch });
console.log('poly area', poly.input.area_sqm, 'fast sources', poly.sources.length, poly.score.grade);
const book = await assessMany(Array.from({ length: 12 }, (_, i) => ({ lat: 21 + i * 0.5, lon: 72 + i * 0.4, asset_type: ['residential', 'agri_land', 'industrial'][i % 3], loan_amount: 1e6 * (i + 1), area_sqm: 1500 })), { fetch }, { mode: 'fast' });
const audit = portfolioAudit(book);
console.log('audit', JSON.stringify({ g: audit.book_grade, w: audit.exposure_weighted_cqs, mix: audit.grade_mix, el: audit.expected_loss_12m, top: audit.concentration.top_district }));
const snap = await pulseSnapshot({ lat: 22.889, lon: 72.223, asset_type: 'agri_land' }, { fetch }, { activity_index: 95, taken_at: '2026-10-01T00:00:00Z' });
console.log('pulse', JSON.stringify(snap));
console.log('OK');
